local function terminal(c)
  local s = require("usgc.colors").std
  local ansi = {
    s.black, s.maroon, s.green, s.olive, s.blue, s.magenta, s.cyan, s.gray,
    s.gray, s.fl_red, s.fl_green, s.fl_yellow, s.fl_blue, s.fl_magenta, s.fl_cyan, s.white,
  }
  for i, col in ipairs(ansi) do
    vim.g['terminal_color_' .. (i - 1)] = col
  end
end

function M.setup(name)
  local c = require("usgc.colors").get(name)
  if vim.g.colors_name then
    vim.cmd("hi clear")
  end
  vim.o.background = 'dark'
  vim.g.colors_name = 'usgc-' .. name
  hl_editor(c)
  hl_syntax(c)
  hl_ts(c)
  hl_lsp(c)
  terminal(c)
end

