function M.setup()
   if vim.g.colors_name then
      vim.cmd("hi clear")
   end
   vim.g.colors_name = "eldritch-linkarzu"
   for group, opts in pairs(syntax_highlight) do
      hi(group, opts)
   end
end

return M
